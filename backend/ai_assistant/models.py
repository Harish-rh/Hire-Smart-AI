from django.db import models
from django.conf import settings
from applications.models import Application
from jobs.models import Job
from candidates.models import Candidate

class ResumeAnalysis(models.Model):
    class Status(models.TextChoices):
        PENDING = 'PENDING', 'Pending'
        PROCESSING = 'PROCESSING', 'Processing'
        COMPLETED = 'COMPLETED', 'Completed'
        FAILED = 'FAILED', 'Failed'

    application = models.ForeignKey(
        Application,
        on_delete=models.CASCADE,
        related_name='resume_analyses',
    )
    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.PENDING,
        db_index=True,
    )
    summary = models.TextField(blank=True)
    skills_found = models.JSONField(default=list, blank=True)
    requirement_evidence = models.JSONField(default=list, blank=True)
    requirements_not_evidenced = models.JSONField(default=list, blank=True)
    clarification_questions = models.JSONField(default=list, blank=True)
    review_required = models.BooleanField(
        default=True,
        help_text="Requires recruiter human review before decisions are made",
    )
    model_name = models.CharField(max_length=100, default='llama3.2:1b')
    prompt_version = models.CharField(max_length=20, default='v1.0')
    is_rule_based = models.BooleanField(
        default=False,
        help_text="True if generated by local deterministic fallback instead of LLM",
    )
    error_message = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"Analysis for App #{self.application_id} [{self.get_status_display()}]"


class InterviewQuestionSet(models.Model):
    class Difficulty(models.TextChoices):
        BEGINNER = 'BEGINNER', 'Beginner'
        INTERMEDIATE = 'INTERMEDIATE', 'Intermediate'
        ADVANCED = 'ADVANCED', 'Advanced'

    job = models.ForeignKey(Job, on_delete=models.CASCADE, related_name='question_sets')
    candidate = models.ForeignKey(
        Candidate,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='question_sets',
    )
    topic = models.CharField(max_length=150, db_index=True)
    difficulty = models.CharField(
        max_length=20,
        choices=Difficulty.choices,
        default=Difficulty.INTERMEDIATE,
    )
    questions = models.JSONField(
        default=list,
        help_text="List of questions with evaluation points and suggested answers",
    )
    is_ai_generated = models.BooleanField(
        default=True,
        help_text="True if generated via local AI, False if selected from verified question bank",
    )
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='created_question_sets',
    )
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.topic} ({self.get_difficulty_display()}) - Job: {self.job.title}"
